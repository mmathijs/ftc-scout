import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Kind, parse, print, stripIgnoredCharacters, visit } from "graphql";

const here = dirname(fileURLToPath(import.meta.url));
const docsDirs = [join(here, "../../web/src/lib/graphql"), join(here, "../src/api/graphql")];
const outFile = join(here, "../src/api/generated/documents.ts");

function graphqlFiles(dir) {
    return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
        e.isDirectory()
            ? graphqlFiles(join(dir, e.name))
            : e.name.endsWith(".graphql")
            ? [join(dir, e.name)]
            : []
    );
}

const TYPENAME = { kind: Kind.FIELD, name: { kind: Kind.NAME, value: "__typename" } };

function addTypename(doc) {
    return visit(doc, {
        SelectionSet: {
            enter(node, _key, parent) {
                if (parent && parent.kind == Kind.OPERATION_DEFINITION) return undefined;
                let has = node.selections.some(
                    (s) => s.kind == Kind.FIELD && s.name.value == "__typename"
                );
                return has ? undefined : { ...node, selections: [...node.selections, TYPENAME] };
            },
        },
    });
}

let definitions = docsDirs
    .flatMap(graphqlFiles)
    .sort()
    .flatMap((f) => parse(readFileSync(f, "utf8")).definitions);
let fragments = new Map(
    definitions.filter((d) => d.kind == Kind.FRAGMENT_DEFINITION).map((d) => [d.name.value, d])
);
let operations = definitions.filter((d) => d.kind == Kind.OPERATION_DEFINITION);

function fragmentsOf(def, seen = new Set()) {
    visit(def, {
        FragmentSpread(node) {
            let name = node.name.value;
            if (seen.has(name)) return;
            let frag = fragments.get(name);
            if (!frag) throw new Error(`Unknown fragment ${name}`);
            seen.add(name);
            fragmentsOf(frag, seen);
        },
    });
    return [...seen].sort().map((n) => fragments.get(n));
}

const SUFFIX = { query: "Query", mutation: "Mutation", subscription: "Subscription" };

let out = [
    "// Generated by scripts/gen-documents.mjs. Do not edit.",
    'import type { Doc } from "../doc";',
    'import type * as T from "./types";',
    "",
    "export type { Doc };",
    "",
];
for (let op of operations) {
    let name = op.name.value;
    let doc = addTypename({ kind: Kind.DOCUMENT, definitions: [op, ...fragmentsOf(op)] });
    let query = stripIgnoredCharacters(print(doc));
    let hash = createHash("sha256").update(query).digest("hex");
    let ty = `${name}${SUFFIX[op.operation]}`;
    out.push(
        `export const ${name}Doc: Doc<T.${ty}, T.${ty}Variables> = {`,
        `    name: ${JSON.stringify(name)},`,
        `    kind: ${JSON.stringify(op.operation)},`,
        `    hash: ${JSON.stringify(hash)},`,
        `    query: ${JSON.stringify(query)},`,
        "};",
        ""
    );
}
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out.join("\n"));
console.log(`Wrote ${operations.length} operations to ${outFile}`);
