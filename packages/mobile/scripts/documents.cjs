// Codegen graphql
const { createHash } = require("node:crypto");
const { Kind, print, stripIgnoredCharacters, visit } = require("graphql");

const TYPENAME = { kind: Kind.FIELD, name: { kind: Kind.NAME, value: "__typename" } };
const SUFFIX = { query: "Query", mutation: "Mutation", subscription: "Subscription" };

function addTypename(doc) {
    return visit(doc, {
        SelectionSet(node, _key, parent) {
            if (parent.kind == Kind.OPERATION_DEFINITION) return undefined;
            let has = node.selections.some(
                (s) => s.kind == Kind.FIELD && s.name.value == "__typename"
            );
            return has ? undefined : { ...node, selections: [...node.selections, TYPENAME] };
        },
    });
}

module.exports = {
    plugin(_schema, documents) {
        let definitions = documents.flatMap((d) => d.document.definitions);
        let fragments = new Map();
        for (let d of definitions) {
            if (d.kind != Kind.FRAGMENT_DEFINITION) continue;
            if (fragments.has(d.name.value)) throw new Error(`Two fragments named ${d.name.value}`);
            fragments.set(d.name.value, d);
        }

        // The fragments an operation uses, and the ones they use.
        let fragmentsOf = (def, seen = new Set()) => {
            visit(def, {
                FragmentSpread({ name: { value } }) {
                    if (seen.has(value)) return;
                    seen.add(value);
                    fragmentsOf(fragments.get(value), seen);
                },
            });
            return [...seen].sort().map((name) => fragments.get(name));
        };

        let out = [
            "// Generated by scripts/documents.cjs (npm run gen). Do not edit.",
            'import type * as T from "./types";',
            "",
            "/** An operation as the API is sent it. `hash` is the SHA-256 of `query`. */",
            "export type Doc<Data, Variables> = {",
            "    name: string;",
            '    kind: "query" | "mutation" | "subscription";',
            "    hash: string;",
            "    query: string;",
            "    /** Never set: carries the types. */",
            "    __types?: (v: Variables) => Data;",
            "};",
        ];
        for (let op of definitions.filter((d) => d.kind == Kind.OPERATION_DEFINITION)) {
            let name = op.name.value;
            let doc = { kind: Kind.DOCUMENT, definitions: [op, ...fragmentsOf(op)] };
            let query = stripIgnoredCharacters(print(addTypename(doc)));
            let hash = createHash("sha256").update(query).digest("hex");
            let ty = `T.${name}${SUFFIX[op.operation]}`;
            out.push(
                "",
                `export const ${name}Doc: Doc<${ty}, ${ty}Variables> = {`,
                `    name: ${JSON.stringify(name)},`,
                `    kind: "${op.operation}",`,
                `    hash: "${hash}",`,
                `    query: ${JSON.stringify(query)},`,
                "};"
            );
        }
        return out.join("\n") + "\n";
    },
};
